def prompt_style(cfg: dict[str, Any]) -> str:
    """判定当前使用的提示词风格：quote_first | legacy。

    answer.prompt_style 优先；旧旋钮 answer.quote_first=false 等价于 legacy。
    """
    a_cfg = (cfg or {}).get("answer", {}) or {}
    style = str(a_cfg.get("prompt_style", "quote_first") or "quote_first").strip().lower()
    if style not in ("quote_first", "legacy"):
        style = "quote_first" if a_cfg.get("quote_first", True) else "legacy"
    elif a_cfg.get("quote_first") is False:
        style = "legacy"
    return style


def bridge_max(cfg: dict[str, Any]) -> int:
    """quote_first 提示词里的衔接语剂量上限（answer.bridge_max_chars，默认 60 字）。"""
    return int(((cfg or {}).get("answer", {}) or {}).get("bridge_max_chars", 60))


def point_prompt(cfg: dict[str, Any]) -> str:
    return PROMPT_TEMPLATE_QUOTE_FIRST if prompt_style(cfg) == "quote_first" else PROMPT_TEMPLATE_LEGACY


def theme_prompt(cfg: dict[str, Any]) -> str:
    return THEME_PROMPT_QUOTE_FIRST if prompt_style(cfg) == "quote_first" else THEME_PROMPT_LEGACY


